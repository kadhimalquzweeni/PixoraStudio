    private static int[] Get(int[][] tables, int index)
    {
        if ((uint)index >= (uint)tables.Length)
            throw new ArgumentOutOfRangeException(nameof(index), index,
                "AAC sampling-frequency index must be between 0 and 12.");
        return tables[index];
